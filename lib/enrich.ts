async function enrichWithGemini(
  text: string,
  apiKey: string,
  systemPrompt: string,
  model: string,
  temperature: number,
  retried = false
): Promise<string | null> {
  const res = await fetch(
    `https://generativelanguage.googleapis.com/v1beta/models/${model}:generateContent`,
    {
      method: "POST",
      headers: {
        "x-goog-api-key": apiKey,
        "Content-Type": "application/json",
      },
      body: JSON.stringify({
        systemInstruction: { parts: [{ text: systemPrompt }] },
        contents: [{ role: "user", parts: [{ text }] }],
        // Réflexion courte : le réalisateur analyse l'intention avant d'annoter
        generationConfig: {
          temperature,
          maxOutputTokens: 4096,
          thinkingConfig: { thinkingBudget: 512 },
        },
        // Textes séduisants : on désactive les filtres pour éviter les blocages
        safetySettings: [
          { category: "HARM_CATEGORY_HARASSMENT", threshold: "BLOCK_NONE" },
          { category: "HARM_CATEGORY_HATE_SPEECH", threshold: "BLOCK_NONE" },
          { category: "HARM_CATEGORY_SEXUALLY_EXPLICIT", threshold: "BLOCK_NONE" },
          { category: "HARM_CATEGORY_DANGEROUS_CONTENT", threshold: "BLOCK_NONE" },
        ],
      }),
      signal: AbortSignal.timeout(TIMEOUT_MS),
    }
  );
  if (!res.ok) {
    const body = await res.text().catch(() => "");
    // Quota par minute dépassé : Google indique le délai ; s'il est court on attend
    const wait = Number(body.match(/retry in ([\d.]+)s/i)?.[1] ?? NaN);
    if ((res.status === 429 || res.status === 503) && wait > 0 && wait <= 10 && !retried) {
      await new Promise((r) => setTimeout(r, wait * 1000 + 300));
      return enrichWithGemini(text, apiKey, systemPrompt, model, temperature, true);
    }
    console.error(`Gemini ${model} ${res.status}:`, body.slice(0, 300));
    return null;
  }
  const data = (await res.json()) as {
    candidates?: { content?: { parts?: { text?: string; thought?: boolean }[] }; finishReason?: string }[];
    promptFeedback?: { blockReason?: string };
  };
  const cand = data.candidates?.[0];
  const out = cand?.content?.parts
    ?.filter((p) => !p.thought)
    .map((p) => p.text ?? "")
    .join("")
    .trim();
  if (!out) {
    console.error(
      `Gemini ${model} refus: ${cand?.finishReason ?? data.promptFeedback?.blockReason ?? "vide"}`
    );
  }
  return out || null;
}

// xAI Grok (API compatible OpenAI)
async function enrichWithGrok(
  text: string,
  apiKey: string,
  systemPrompt: string,
  model: string,
  temperature: number,
  retried = false
): Promise<string | null> {
  const res = await fetch("https://api.x.ai/v1/chat/completions", {
    method: "POST",
    headers: { Authorization: `Bearer ${apiKey}`, "Content-Type": "application/json" },
    body: JSON.stringify({
      model,
      temperature,
      max_tokens: 2048,
      messages: [
        { role: "system", content: systemPrompt },
        { role: "user", content: text },
      ],
    }),
    signal: AbortSignal.timeout(TIMEOUT_MS),
  });
  if (!res.ok) {
    console.error(`Grok ${model} ${res.status}:`, (await res.text().catch(() => "")).slice(0, 300));
    if ((res.status === 429 || res.status >= 500) && !retried) {
      await new Promise((r) => setTimeout(r, 1500));
      return enrichWithGrok(text, apiKey, systemPrompt, model, temperature, true);
    }
    return null;
  }
  const data = (await res.json()) as { choices?: { message?: { content?: string } }[] };
  return data.choices?.[0]?.message?.content?.trim() || null;
}

