/** Ancien niveau (0 à 3) → 🌶 ou 🌶🌶 */
export function normalizeLevel(level: number | null | undefined): number {
  return Number(level) >= 2 ? 2 : 1;
}

export const DEFAULT_INTENSITY = 1;

