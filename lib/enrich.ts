async function enrichWithClaude(
  text: string,
  apiKey: string,
  systemPrompt: string
): Promise<string | null> {
  const client = new Anthropic({ apiKey, timeout: TIMEOUT_MS, maxRetries: 1 });
  const response = await client.messages.create({
    model: "claude-opus-4-8",
    max_tokens: 2000,
    system: systemPrompt,
    messages: [{ role: "user", content: text }],
  });
  return (
    response.content.find((block) => block.type === "text")?.text.trim() ?? null
  );
}

// ── Contrôle de la mise en scène ─────────────────────────────────────────────
const EMOJI = /[\p{Extended_Pictographic}\u{FE0F}\u{200D}]/gu;

/** Les mots réellement dits (sans mise en scène, ponctuation ni emojis) */
// Gémissements / interjections (« ahh », « mmh », « oh ») : le LLM peut en
// ajouter au niveau 🌶🌶, ce ne sont pas des mots du message
const INTERJECTION = /^(a+h*|o+h+|o+|m+h*|h+m+|h+a+h*|n+h+|h+n+|u+h+|ou+h+|ha(ha)+|hi(hi)+)$/;

export function spokenWords(text: string): string[] {
  return text
    .replace(/\[[^\]]*\]/g, " ")
    .replace(/<\/?[a-z]+>/gi, " ")
    .replace(EMOJI, " ")
    .normalize("NFC")
    .toLowerCase()
    .replace(/[’`]/g, "'")
    .split(/[^\p{L}\p{N}'⟦⟧]+/u)
    .map((w) => w.replace(/^'+|'+$/g, ""))
    .filter((w) => w && !INTERJECTION.test(w));
}

/**
 * Vérifie et répare la sortie du LLM. null si elle est inutilisable :
 * mots changés, balises inconnues ou mal fermées, mise en scène trop chargée.
 */
export function checkDirected(input: string, output: string, level = DEFAULT_INTENSITY): string | null {
  let out = output
    .replace(/^```[a-z]*\s*|\s*```$/g, "")
    .replace(/^["«]\s*|\s*["»]$/g, "")
    .replace(/\s*\n+\s*/g, " ")
    .trim();
  // Balises de mot : seules les connues, jamais imbriquées, toujours fermées
  const tags = [...out.matchAll(/<(\/?)([a-z]+)>/gi)];
  let open: string | null = null;
  for (const [, slash, name] of tags) {
    const n = name.toLowerCase();
    if (!PAIRED.includes(n)) return null;
    if (!slash) {
      if (open) return null;
      open = n;
    } else {
      if (open !== n) return null;
      open = null;
    }
  }
  if (open) return null;
  // Mêmes mots, dans le même ordre (🌶🌶 : quelques répétitions de mots du texte permises)
  const a = spokenWords(input);
  const b = spokenWords(out);
  const same = a.length === b.length && a.every((w, i) => w === b[i]);
  if (!same) {
    if (normalizeLevel(level) !== 2) return null;
    const vocab = new Set(a);
    let k = 0;
    for (const w of b) if (k < a.length && w === a[k]) k++;
    const onlyRepeats = k === a.length && b.every((w) => vocab.has(w));
    if (!onlyRepeats || b.length > a.length * 1.5 + 2) return null;
  }
  // Directions et sons : pas de crochet vide, pas de pavé, densité raisonnable
  const brackets = [...out.matchAll(/\[([^\]]*)\]/g)].map((m) => m[1].trim());
  if (brackets.some((d) => !d || d.split(/\s+/).length > 12)) return null;
  const maxMarks = normalizeLevel(level) === 2 ? 4 + a.length : 3 + Math.ceil(a.length / 3);
  if (brackets.length > maxMarks) return null;
  // Emojis restants retirés (ils ne se disent pas)
  out = out.replace(EMOJI, "").replace(/\s{2,}/g, " ").trim();
  // Pas de voix qui traîne : « slow / slowing down » retirés des directions, <slow> enlevé
  out = out
    .replace(/<\/?slow>/gi, "")
    .replace(/\[([^\]]*)\]/g, (m, d: string) => {
      if (!/slow|drawn|drawl|lingering/i.test(d)) return m;
      const kept = d.split(",").map((x) => x.trim()).filter((x) => x && !/slow|drawn|drawl|lingering/i.test(x));
      return kept.length ? `[${kept.join(", ")}]` : "";
    });
  // Pas de longs silences : 1 seule pause courte, 1 seul « … » (les autres → virgule)
  let pauses = 0;
  out = out.replace(/\[[^\]]*pause[^\]]*\]\s*/gi, () => (pauses++ === 0 ? "[short pause] " : ""));
  let dots = 0;
  out = out.replace(/…|\.{3,}/g, () => (dots++ === 0 ? "…" : ","));
  out = out.replace(/,\s*([,.!?])/g, "$1").replace(/\s{2,}/g, " ").trim();
  return out;
}

/**
 * ✏️ Le chatter demande une retouche (« moins de rires », « plus chaud »…) :
 * l'IA modifie la mise en scène existante, sans toucher aux mots.
 * null si impossible (pas de clé, refus, mots changés).
 */
export async function reviseDirection(
  directed: string,
  request: string,
  level: number = DEFAULT_INTENSITY
): Promise<string | null> {
  const key = process.env.XAI_API_KEY;
  if (!key) return null;
  const system =
    buildSystemPrompt(level) +
    "\n\nREVISION MODE: you receive an already directed text and the chatter's change request (any language). " +
    "Apply the request to the directions, sounds and word tags only. The spoken words stay exactly the same. " +
    "Output ONLY the revised directed text.";
  const user = `CURRENT:\n${directed}\n\nCHANGE REQUEST:\n${request.slice(0, 300)}`;
  for (const temperature of [0.6, 0.9]) {
    try {
      const raw = await enrichWithGrok(user, key, system, process.env.XAI_MODEL?.trim() || GROK_MODEL, temperature);
      if (!raw || REFUSAL.test(raw)) continue;
      const checked = checkDirected(directed, raw.replace(/^REVISED:?\s*/i, ""), 2);
      if (checked) return checked;
      console.error("Retouche rejetée:", JSON.stringify({ directed, request, raw }));
    } catch (err) {
      console.error("Retouche échouée:", err);
    }
  }
  return null;
}

/**
 * Met en scène le texte pour Drama 3 selon le niveau d'intensité (0 à 3).
 * Retourne le texte d'origine si :
 * - aucune clé LLM n'est configurée
 * - le texte contient déjà une mise en scène (l'opérateur l'a faite lui-même)
 * - le LLM échoue, dépasse le délai ou change les mots
 */
export async function enrichWithEmotionTags(
  rawText: string,
  level: number = DEFAULT_INTENSITY,
  variety = false,
  _styleKey?: string,
  lang: "fr" | "en" | "de" = "fr"
): Promise<string> {
  // Mise en scène écrite par l'opérateur : gardée telle quelle
  if (EXISTING_TAG.test(rawText)) return rawText;
  // « mdr », « tkt »… → vrais mots, sinon la voix les épelle
  const text = speakable(rawText, lang);

  const xaiKey = process.env.XAI_API_KEY;
  const geminiKey = process.env.GEMINI_API_KEY;
  const groqKey = process.env.GROQ_API_KEY;
  const anthropicKey = process.env.ANTHROPIC_API_KEY;
  if (!xaiKey && !geminiKey && !groqKey && !anthropicKey) return text;

  const systemPrompt = buildSystemPrompt(level);

  // 1) Grok : texte INTACT (il accepte les textes adultes), donc il comprend
  //    vraiment le message ; 2 modèles avant de passer à Gemini.
  // Mots crus masqués (⟦T0⟧…) : sert si l'IA refuse le texte intact
  const maskFr = maskSensitiveFr(text);
  const maskBoth = maskSensitiveEn(maskFr.masked);
  const table = new Map([...maskFr.table, ...maskBoth.table]);
  const masked = maskBoth.masked;

  if (xaiKey) {
    const model = process.env.XAI_MODEL?.trim() || GROK_MODEL;
    // 1) texte intact ; 2) si refus, texte masqué (Grok ne refuse plus)
    const tries: [string, number][] = [[text, variety ? 0.9 : 0.7]];
    if (masked !== text) tries.push([masked, 0.8]);
    else tries.push([text, 1.0]);
    for (const [input, temperature] of tries) {
      try {
        const raw = await enrichWithGrok(input, xaiKey, systemPrompt, model, temperature);
        if (raw && REFUSAL.test(raw)) {
          console.error("Grok refuse:", raw.slice(0, 80));
          continue;
        }
        const checked = raw ? checkDirected(input, raw, level) : null;
        if (checked) {
          const restored = input === masked ? unmask(checked, table) : checked;
          if (!LEFTOVER.test(restored)) return restored;
        }
        console.error("Mise en scène Grok rejetée:", JSON.stringify({ model, input, raw }));
      } catch (err) {
        console.error(`Mise en scène Grok ${model} échouée:`, err);
      }
    }
    // Grok en place : pas de détour par Gemini (quota gratuit saturé = attente)
    return text;
  }
  if (!geminiKey && !groqKey && !anthropicKey) return text;

  // Meilleur modèle d'abord, puis un plus rapide si refus / mots changés
  const attempts: [string, number][] = [
    [process.env.ENRICH_MODEL?.trim() || "gemini-flash-latest", variety ? 0.9 : 0.6],
    ["gemini-flash-latest", 0.8],
    ["gemini-flash-lite-latest", 0.5],
  ];

  for (const [model, temperature] of attempts) {
    try {
      const raw = geminiKey
        ? await enrichWithGemini(masked, geminiKey, systemPrompt, model, temperature)
        : groqKey
          ? await enrichWithGroq(masked, groqKey, systemPrompt)
          : await enrichWithClaude(masked, anthropicKey!, systemPrompt);
      const checked = raw ? checkDirected(masked, raw, level) : null;
      if (!checked) {
        console.error("Mise en scène rejetée:", JSON.stringify({ model, masked, raw }));
        continue;
      }
      const restored = unmask(checked, table);
      if (LEFTOVER.test(restored)) {
        console.error("Mise en scène rejetée (jeton perdu):", JSON.stringify({ restored }));
        continue;
      }
      return restored;
    } catch (err) {
      console.error(`Mise en scène ${model} échouée (essai suivant):`, err);
    }
  }
  console.error("Mise en scène impossible après 3 essais, texte brut utilisé");
  return text;
}
